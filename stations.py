DEFAULT_DATASET = "广州地铁2027"


def list_datasets():
    return list(STATION_DATASETS.keys())


def get_dataset(name=None):
    if name is None:
        name = DEFAULT_DATASET
    return STATION_DATASETS.get(name)


def get_all_stations(dataset=None):
    data = get_dataset(dataset)
    if data:
        return data["stations"].copy()
    return set()


def get_stations_by_line(line_name, dataset=None):
    data = get_dataset(dataset)
    if data:
        return data["stations_by_line"].get(line_name, [])
    return []


def get_all_lines(dataset=None):
    data = get_dataset(dataset)
    if data:
        return data["stations_by_line"]
    return {}


def get_card_lines(dataset=None):
    data = get_dataset(dataset)
    if data:
        return data.get("card_lines", {})
    return {}


def get_districts(dataset=None):
    data = get_dataset(dataset)
    if data:
        return data.get("stations_by_district", {})
    return {}
